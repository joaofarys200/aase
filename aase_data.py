def analisar_valores_csv(dataset):
    df = pd.read_csv(dataset)
    resultado = []
    for coluna in df.columns:
        nulos = df[coluna].isnull().sum()
        em_branco = (df[coluna] == '').sum() if df[coluna].dtype == object else 0
        distintos = df[coluna].nunique(dropna=True)
        unicos = (df[coluna].value_counts() == 1).sum()
        duplicados = len(df[coluna]) - df[coluna].nunique(dropna=False)
        resultado.append({
            'Atributo': coluna,
            'Nulos': nulos,
            'Em Branco': em_branco,
            'Distintos': distintos,
            'Únicos': unicos,
            'Duplicados': duplicados
        })
    return pd.DataFrame(resultado)

