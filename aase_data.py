num_cols = df_clean.select_dtypes(include=[np.number]).columns

normality_results = []

print("Teste de Shapiro–Wilk (α = 0.05)\n")

for col in num_cols:
    # Teste só se a coluna tiver pelo menos 3 valores válidos
    if df_clean[col].notna().sum() >= 3:
        stat, p = shapiro(df_clean[col].dropna())
        interpretation = "Normal" if p > 0.05 else "Não normal"
        normality_results.append([col, stat, p, interpretation])
        print(f"{col:<35} | p = {p:.4f} → {interpretation}")

# Guardar resultados num DataFrame para referência
df_normality = pd.DataFrame(normality_results, columns=["Variável", "Estatística", "p-valor", "Interpretação"])

display(df_normality)

# Verificar se o target é normal ou não
target_p = df_normality.loc[df_normality["Variável"] == target, "p-valor"].values[0]
if target_p > 0.05:
    print(f"O target '{target}' parece normal (p={target_p:.3f}) — aplicando IQR para outliers.")
else:
    print(f"O target '{target}' NÃO parece normal (p={target_p:.3f}) — manter valores extremos para cenário 1 e cenário 2.")